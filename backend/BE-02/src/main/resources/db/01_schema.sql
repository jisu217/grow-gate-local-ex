CREATE TABLE IF NOT EXISTS public_data_collection_runs (
    id VARCHAR(36) PRIMARY KEY,
    diagnosis_id VARCHAR(36),
    requested_by VARCHAR(36),
    hs_code VARCHAR(20),
    target_country VARCHAR(40),
    product_name VARCHAR(160),
    status VARCHAR(20) NOT NULL,
    provider_count INTEGER NOT NULL DEFAULT 0,
    success_count INTEGER NOT NULL DEFAULT 0,
    fallback_count INTEGER NOT NULL DEFAULT 0,
    cache_hit_count INTEGER NOT NULL DEFAULT 0,
    error_summary TEXT,
    started_at TIMESTAMP NOT NULL,
    finished_at TIMESTAMP,
    CONSTRAINT fk_public_data_runs_user FOREIGN KEY (requested_by) REFERENCES users(id)
);

CREATE TABLE IF NOT EXISTS public_data_records (
    id VARCHAR(36) PRIMARY KEY,
    run_id VARCHAR(36),
    provider VARCHAR(40) NOT NULL,
    endpoint VARCHAR(500),
    request_key VARCHAR(240) NOT NULL,
    hs_code VARCHAR(20),
    target_country VARCHAR(40),
    matched_key VARCHAR(500),
    used_for VARCHAR(60),
    raw_payload TEXT,
    normalized_payload TEXT,
    score_contribution INTEGER,
    confidence DOUBLE PRECISION,
    source_type VARCHAR(20),
    source_quality_status VARCHAR(40),
    fallback_used BOOLEAN NOT NULL DEFAULT FALSE,
    cache_hit BOOLEAN NOT NULL DEFAULT FALSE,
    error_message TEXT,
    fetched_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP,
    CONSTRAINT fk_public_data_records_run FOREIGN KEY (run_id) REFERENCES public_data_collection_runs(id)
);

CREATE INDEX IF NOT EXISTS idx_public_data_runs_requested_by_started
    ON public_data_collection_runs (requested_by, started_at DESC);

CREATE INDEX IF NOT EXISTS idx_public_data_records_scope_fetched
    ON public_data_records (run_id, hs_code, target_country, fetched_at DESC);

CREATE INDEX IF NOT EXISTS idx_public_data_records_cache
    ON public_data_records (provider, request_key, expires_at DESC);

CREATE TABLE IF NOT EXISTS user_consent_records (
    id VARCHAR(36) PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL,
    policy_version VARCHAR(40) NOT NULL,
    terms_accepted BOOLEAN NOT NULL DEFAULT FALSE,
    privacy_accepted BOOLEAN NOT NULL DEFAULT FALSE,
    marketing_accepted BOOLEAN NOT NULL DEFAULT FALSE,
    accepted_at TIMESTAMP NOT NULL,
    withdrawn_at TIMESTAMP,
    source VARCHAR(40) NOT NULL DEFAULT 'signup',
    CONSTRAINT fk_user_consent_user FOREIGN KEY (user_id) REFERENCES users(id)
);

CREATE INDEX IF NOT EXISTS idx_user_consent_user_accepted
    ON user_consent_records (user_id, accepted_at);

CREATE TABLE IF NOT EXISTS external_source_documents (
    id VARCHAR(36) PRIMARY KEY,
    diagnosis_id VARCHAR(36),
    provider VARCHAR(80) NOT NULL,
    source_type VARCHAR(20) NOT NULL,
    source_url VARCHAR(700),
    document_title VARCHAR(300),
    content_hash VARCHAR(128),
    fetched_at TIMESTAMP NOT NULL,
    published_at TIMESTAMP,
    raw_ref VARCHAR(120),
    normalized_payload TEXT,
    CONSTRAINT fk_external_source_documents_diagnosis FOREIGN KEY (diagnosis_id) REFERENCES diagnosis_runs(id)
);

CREATE TABLE IF NOT EXISTS evidence_claims (
    id VARCHAR(36) PRIMARY KEY,
    diagnosis_id VARCHAR(36),
    source_document_id VARCHAR(36),
    claim_text TEXT NOT NULL,
    source_id VARCHAR(160) NOT NULL,
    claim_type VARCHAR(40),
    confidence DOUBLE PRECISION,
    verifier_status VARCHAR(30) NOT NULL,
    rejection_reason TEXT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_evidence_claims_diagnosis FOREIGN KEY (diagnosis_id) REFERENCES diagnosis_runs(id),
    CONSTRAINT fk_evidence_claims_source_document FOREIGN KEY (source_document_id) REFERENCES external_source_documents(id)
);

CREATE TABLE IF NOT EXISTS temporal_events (
    id VARCHAR(36) PRIMARY KEY,
    diagnosis_id VARCHAR(36),
    source_document_id VARCHAR(36),
    event_type VARCHAR(80) NOT NULL,
    event_time TIMESTAMP,
    period_start TIMESTAMP,
    period_end TIMESTAMP,
    summary TEXT,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_temporal_events_diagnosis FOREIGN KEY (diagnosis_id) REFERENCES diagnosis_runs(id),
    CONSTRAINT fk_temporal_events_source_document FOREIGN KEY (source_document_id) REFERENCES external_source_documents(id)
);

CREATE TABLE IF NOT EXISTS knowledge_pages (
    id VARCHAR(36) PRIMARY KEY,
    product_id VARCHAR(36),
    diagnosis_id VARCHAR(36),
    page_type VARCHAR(40) NOT NULL,
    country VARCHAR(40),
    hs_code VARCHAR(20),
    industry VARCHAR(80),
    title VARCHAR(240) NOT NULL,
    markdown TEXT NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    CONSTRAINT fk_knowledge_pages_product FOREIGN KEY (product_id) REFERENCES products(id),
    CONSTRAINT fk_knowledge_pages_diagnosis FOREIGN KEY (diagnosis_id) REFERENCES diagnosis_runs(id)
);

CREATE TABLE IF NOT EXISTS agent_trace_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    agent_run_id VARCHAR(64) NOT NULL,
    diagnosis_id VARCHAR(36) NOT NULL,
    step_no INTEGER NOT NULL,
    agent_name VARCHAR(80) NOT NULL,
    tool_name VARCHAR(160) NOT NULL,
    input_hash VARCHAR(96),
    output_schema VARCHAR(120),
    output_summary VARCHAR(1000),
    source_type VARCHAR(32) NOT NULL,
    provider VARCHAR(80),
    endpoint VARCHAR(500),
    latency_ms BIGINT,
    status VARCHAR(32) NOT NULL,
    retry_count INTEGER NOT NULL DEFAULT 0,
    fallback_reason VARCHAR(1000),
    evidence_count INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_agent_trace_events_diagnosis FOREIGN KEY (diagnosis_id) REFERENCES diagnosis_runs(id)
);

CREATE INDEX IF NOT EXISTS idx_evidence_claims_diagnosis_status
    ON evidence_claims (diagnosis_id, verifier_status);

CREATE INDEX IF NOT EXISTS idx_knowledge_pages_product_type
    ON knowledge_pages (product_id, page_type, updated_at DESC);

CREATE TABLE IF NOT EXISTS revoked_tokens (
    token_hash VARCHAR(64) PRIMARY KEY,
    expires_at TIMESTAMP NOT NULL,
    created_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_revoked_tokens_expires_at
    ON revoked_tokens (expires_at);
